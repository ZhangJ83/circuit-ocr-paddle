#!/usr/bin/env python3
"""
GitHub Repository License Checker
=================================
Check license compliance for all source repos used in the Circuit OCR dataset.

Supports two input modes:
  1. From scraped_metadata.json  (generated by github_scraper.py)
  2. From a plain text file with one repo URL per line

Output: A report categorizing repos by license risk level.

Usage:
  python scripts/check_licenses.py --metadata data/raw/scraped_metadata.json
  python scripts/check_licenses.py --repos-file repos.txt
  python scripts/check_licenses.py --repos-file repos.txt --github-token ghp_xxx
"""

import argparse
import json
import os
import sys
import time
from pathlib import Path
from typing import Dict, List, Optional, Tuple
from collections import defaultdict


# ---------------------------------------------------------------------------
# License classification
# ---------------------------------------------------------------------------

# Permissive licenses — safe to use, just retain notice
PERMISSIVE = {
    "mit", "apache-2.0", "bsd-2-clause", "bsd-3-clause",
    "bsd-3-clause-clear", "bsd-4-clause", "unlicense", "cc0-1.0",
    "isc", "zlib", "postgresql", "ofl-1.1", "ncsa",
    "osl-3.0", "afl-3.0", "epl-1.0", "epl-2.0", "eupl-1.2",
    "wtfpl", "0bsd", "mpl-2.0", "lgpl-2.1", "lgpl-3.0",
    "artistic-2.0",
}

# Weak copyleft / hardware-specific — may need same-license for derivatives
# CERN OHL v2 has three variants
CAUTION = {
    "gpl-2.0", "gpl-3.0", "agpl-3.0",
    "cc-by-sa-4.0", "cc-by-sa-3.0",
    "cern-ohl-2.0-s",          # Strong reciprocal — derivatives must use same license
    "cern-ohl-2.0-w",          # Weak reciprocal
    "cern-ohl-1.2",
    "mpl-1.1",
    "eupl-1.1",
}

# Dangerous / unusable — do NOT include in dataset
DANGEROUS = {
    "cc-by-nc-4.0", "cc-by-nc-3.0", "cc-by-nc-2.0",
    "cc-by-nd-4.0", "cc-by-nc-nd-4.0",
    "rsa-md5",
    "other",                    # Non-standard licenses need manual review
}

# Hardware design licenses commonly found on KiCad projects
HARDWARE_PERMISSIVE = {
    "cern-ohl-2.0-p",          # Permissive — fine to use
    "cern-ohl-p-2.0",
    "solderpad-2.1",
    "tapr-ohl-1.0",
}


def classify_license(license_key: Optional[str]) -> Tuple[str, str]:
    """
    Classify a GitHub license key.

    Returns (risk_level, description)
      risk_level: "safe" | "caution" | "dangerous" | "unknown"
    """
    if not license_key:
        return ("dangerous", "No license -- all rights reserved. CANNOT USE.")

    key = license_key.lower().strip()

    if key in PERMISSIVE or key in HARDWARE_PERMISSIVE:
        return ("safe", f"{license_key} -- freely usable with attribution.")

    if key in CAUTION:
        if "gpl" in key or "agpl" in key:
            return ("caution",
                    f"{license_key} -- copyleft; derivative works must be {license_key}. "
                    "Rendering schematics as images may count as derivative.")
        if "cc-by-sa" in key:
            return ("caution",
                    f"{license_key} -- must attribute + share-alike. "
                    "Dataset may need same license.")
        if "cern-ohl" in key and ("s" in key or "strong" in key.lower()):
            return ("caution",
                    f"{license_key} -- strong reciprocal for hardware. Review needed.")
        return ("caution", f"{license_key} -- review terms before use.")

    if key in DANGEROUS:
        if "nc" in key:
            return ("dangerous",
                    f"{license_key} -- NON-COMMERCIAL. Cannot use in competition/benchmark.")
        if "nd" in key:
            return ("dangerous",
                    f"{license_key} -- NO DERIVATIVES. Cannot create rendered images.")
        return ("dangerous", f"{license_key} -- incompatible with open dataset release.")

    return ("unknown", f"{license_key} -- manual review required.")


# ---------------------------------------------------------------------------
# GitHub API client (no external deps needed)
# ---------------------------------------------------------------------------

class GitHubLicenseChecker:
    """Check licenses for a list of GitHub repos using the REST API."""

    API_BASE = "https://api.github.com"

    def __init__(self, github_token: Optional[str] = None):
        self.token = github_token or os.environ.get("GITHUB_TOKEN")
        self.session = None  # lazy import

    def _get(self, url: str) -> dict:
        """Make an authenticated GET request to GitHub API."""
        import urllib.request
        import urllib.error

        headers = {
            "Accept": "application/vnd.github.v3+json",
            "User-Agent": "circuit-ocr-license-checker/1.0",
        }
        if self.token:
            headers["Authorization"] = f"Bearer {self.token}"

        req = urllib.request.Request(url, headers=headers)
        try:
            with urllib.request.urlopen(req, timeout=15) as resp:
                remaining = resp.headers.get("X-RateLimit-Remaining")
                if remaining and int(remaining) < 5:
                    reset = int(resp.headers.get("X-RateLimit-Reset", time.time() + 60))
                    wait = max(reset - time.time(), 1)
                    print(f"  Rate limit low, sleeping {wait:.0f}s...")
                    time.sleep(wait)
                return json.loads(resp.read().decode())
        except urllib.error.HTTPError as e:
            if e.code == 404:
                return {"error": "not_found"}
            if e.code == 403:
                reset = int(e.headers.get("X-RateLimit-Reset", time.time() + 60))
                wait = max(reset - time.time(), 1)
                print(f"  Rate limited, sleeping {wait:.0f}s...")
                time.sleep(wait)
                return self._get(url)
            return {"error": str(e.code)}
        except Exception as e:
            return {"error": str(e)}

    def check_repo(self, owner: str, repo: str) -> dict:
        """Check license for a single repo."""
        url = f"{self.API_BASE}/repos/{owner}/{repo}"
        data = self._get(url)

        if "error" in data:
            return {"owner": owner, "repo": repo, "error": data["error"]}

        license_info = data.get("license")
        license_key = license_info["key"] if license_info else None
        risk, note = classify_license(license_key)

        return {
            "owner": owner,
            "repo": repo,
            "full_name": data.get("full_name", f"{owner}/{repo}"),
            "html_url": data.get("html_url", ""),
            "license": license_key,
            "license_name": license_info["name"] if license_info else "None",
            "risk": risk,
            "note": note,
            "stars": data.get("stargazers_count", 0),
            "archived": data.get("archived", False),
            "description": (data.get("description") or "")[:120],
        }

    def check_from_metadata(self, metadata_path: str) -> List[dict]:
        """Check licenses from a scraped_metadata.json file."""
        with open(metadata_path, "r", encoding="utf-8") as f:
            metadata = json.load(f)

        results = []
        repos_seen = set()

        for entry in metadata:
            repo_name = entry.get("repo_name", "")
            if not repo_name or repo_name in repos_seen:
                continue
            repos_seen.add(repo_name)

            # repo_name is usually "owner/repo"
            if "/" in repo_name:
                owner, repo = repo_name.split("/", 1)
            else:
                # Try to extract from html_url
                html_url = entry.get("repo_url") or entry.get("html_url", "")
                if "github.com/" in html_url:
                    parts = html_url.split("github.com/")[1].rstrip("/").split("/")
                    if len(parts) >= 2:
                        owner, repo = parts[0], parts[1]
                    else:
                        continue
                else:
                    print(f"  SKIP: cannot parse repo name from '{repo_name}'")
                    continue

            print(f"  Checking {owner}/{repo}...")
            result = self.check_repo(owner, repo)
            results.append(result)
            time.sleep(0.3)  # Be polite to GitHub API (unauthenticated: 60/hr)

        return results

    def check_from_file(self, file_path: str) -> List[dict]:
        """Check licenses from a text file (one repo URL or owner/repo per line)."""
        with open(file_path, "r", encoding="utf-8") as f:
            lines = [l.strip() for l in f if l.strip() and not l.startswith("#")]

        results = []
        for line in lines:
            # Parse repo identifier
            if "github.com/" in line:
                parts = line.split("github.com/")[1].rstrip("/").rstrip(".git").split("/")
                if len(parts) >= 2:
                    owner, repo = parts[0], parts[1]
                else:
                    print(f"  SKIP: cannot parse URL '{line}'")
                    continue
            elif "/" in line and not line.startswith("http"):
                owner, repo = line.split("/", 1)
            else:
                print(f"  SKIP: unrecognized format '{line}'")
                continue

            print(f"  Checking {owner}/{repo}...")
            result = self.check_repo(owner, repo)
            results.append(result)
            time.sleep(0.3)

        return results


# ---------------------------------------------------------------------------
# Report generator
# ---------------------------------------------------------------------------

def print_report(results: List[dict], output_json: Optional[str] = None):
    """Print a categorized license report."""
    by_risk = defaultdict(list)
    errors = []

    for r in results:
        if "error" in r:
            errors.append(r)
        else:
            by_risk[r.get("risk", "unknown")].append(r)

    total = len(results)
    safe = len(by_risk["safe"])
    caution = len(by_risk["caution"])
    dangerous = len(by_risk["dangerous"])
    unknown = len(by_risk["unknown"])

    # ---- Summary ----
    print()
    print("=" * 70)
    print("  LICENSE COMPLIANCE REPORT")
    print("=" * 70)
    print(f"  Total repos checked:   {total}")
    print(f"  Errors (not checked):  {len(errors)}")
    print()
    print(f"  [SAFE] Permissive:   {safe}")
    print(f"  [CAUTION] Copyleft:  {caution}")
    print(f"  [DANGEROUS] No/bad:  {dangerous}")
    print(f"  [UNKNOWN] Manual:    {unknown}")
    print("=" * 70)

    # ---- Safe ----
    if by_risk["safe"]:
        print("\n[SAFE] These repos have permissive licenses:")
        for r in sorted(by_risk["safe"], key=lambda x: x["full_name"]):
            print(f"  {r['full_name']:45s}  {r['license']:20s}  stars={r['stars']}")

    # ---- Caution ----
    if by_risk["caution"]:
        print("\n[CAUTION] Copyleft / needs review:")
        for r in sorted(by_risk["caution"], key=lambda x: x["full_name"]):
            print(f"  {r['full_name']:45s}  {r['license']:20s}")
            print(f"    -> {r['note']}")

    # ---- Dangerous ----
    if by_risk["dangerous"]:
        print("\n[DANGEROUS] MUST EXCLUDE from dataset:")
        for r in sorted(by_risk["dangerous"], key=lambda x: x["full_name"]):
            print(f"  {r['full_name']:45s}  {(r['license'] or 'NO LICENSE'):20s}")
            print(f"    -> {r['note']}")

    # ---- Unknown ----
    if by_risk["unknown"]:
        print("\n[UNKNOWN] Manual review needed:")
        for r in sorted(by_risk["unknown"], key=lambda x: x["full_name"]):
            print(f"  {r['full_name']:45s}  {(r['license'] or 'NO LICENSE'):20s}")

    # ---- Errors ----
    if errors:
        print("\n[ERRORS] Could not check:")
        for r in errors:
            print(f"  {r.get('owner','')}/{r.get('repo','')}: {r.get('error','')}")

    # ---- Verdict ----
    print()
    if dangerous > 0:
        print(f"[FAIL] {dangerous} repos have incompatible licenses. "
              f"Remove them before releasing the dataset.")
    elif caution > 0:
        print(f"[WARN] {caution} repos have copyleft licenses. "
              f"Review whether rendering + annotation extraction constitutes derivative work.")
    elif unknown > 0:
        print(f"[WARN] {unknown} repos need manual review. "
              f"Check their license files directly.")
    else:
        print("[PASS] All repos have permissive licenses. Safe to redistribute.")

    # ---- Next steps ----
    print()
    print("Next steps:")
    print("  1. For CAUTION repos: check their actual LICENSE file.")
    print("     Rendering an image + extracting text may be 'fair use' / 'transformative'")
    print("     and not a derivative work, but this varies by jurisdiction.")
    print("  2. Add a SOURCES.md file listing all source repos + licenses.")
    print("  3. In annotation JSONs, add 'source_repo' and 'source_license' fields.")
    print("  4. Consider: is 100% synthetic data sufficient for your needs?")
    print("     If yes, skip GitHub scraping entirely = zero license risk.")

    # Save JSON report
    if output_json:
        report = {
            "summary": {
                "total": total,
                "safe": safe,
                "caution": caution,
                "dangerous": dangerous,
                "unknown": unknown,
                "errors": len(errors),
            },
            "safe": by_risk["safe"],
            "caution": by_risk["caution"],
            "dangerous": by_risk["dangerous"],
            "unknown": by_risk["unknown"],
            "errors": errors,
        }
        with open(output_json, "w", encoding="utf-8") as f:
            json.dump(report, f, indent=2, ensure_ascii=False)
        print(f"\nFull report saved to: {output_json}")


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(
        description="Check GitHub repo licenses for dataset compliance"
    )
    src = parser.add_mutually_exclusive_group(required=True)
    src.add_argument("--metadata", help="Path to scraped_metadata.json")
    src.add_argument("--repos-file", help="Path to text file (one repo per line)")
    parser.add_argument("--github-token", help="GitHub personal access token")
    parser.add_argument("--output-json", default="license_report.json",
                        help="Output JSON report path")
    parser.add_argument("--mock", action="store_true",
                        help="Run in mock mode (no API calls, for testing)")
    args = parser.parse_args()

    checker = GitHubLicenseChecker(github_token=args.github_token)

    if args.mock:
        # Mock data for testing without API calls
        results = [
            {
                "owner": "test", "repo": "mit-project", "full_name": "test/mit-project",
                "html_url": "https://github.com/test/mit-project",
                "license": "mit", "license_name": "MIT License",
                "risk": "safe", "note": "MIT -- freely usable.",
                "stars": 100, "archived": False, "description": "A test repo",
            },
            {
                "owner": "test", "repo": "nolicense-project", "full_name": "test/nolicense-project",
                "html_url": "https://github.com/test/nolicense-project",
                "license": None, "license_name": "None",
                "risk": "dangerous", "note": "No license -- all rights reserved.",
                "stars": 5, "archived": False, "description": "No license repo",
            },
            {
                "owner": "test", "repo": "gpl-project", "full_name": "test/gpl-project",
                "html_url": "https://github.com/test/gpl-project",
                "license": "gpl-3.0", "license_name": "GNU GPL v3.0",
                "risk": "caution",
                "note": "GPL-3.0 -- copyleft; derivative works must be GPL-3.0.",
                "stars": 50, "archived": False, "description": "GPL hardware project",
            },
        ]
        print_report(results, args.output_json)
        return

    if args.metadata:
        results = checker.check_from_metadata(args.metadata)
    else:
        results = checker.check_from_file(args.repos_file)

    print_report(results, args.output_json)


if __name__ == "__main__":
    main()
